#!/usr/bin/env node
/**
 * Generates the JWT secret and the anon / service_role keys that a self-hosted
 * Supabase stack needs, and writes .env.docker.
 *
 *   node scripts/gen-supabase-keys.mjs
 *
 * Run once per deployment. The keys are derived from the secret, so anyone
 * holding the secret can mint a service_role token — treat .env.docker as
 * sensitive and never commit it.
 */
import { createHmac, randomBytes } from "node:crypto";
import { writeFileSync, existsSync } from "node:fs";
import { exit } from "node:process";

const b64url = (buf) =>
  Buffer.from(buf).toString("base64").replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");

function jwt(payload, secret) {
  const header = b64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const body = b64url(JSON.stringify(payload));
  const sig = b64url(createHmac("sha256", secret).update(`${header}.${body}`).digest());
  return `${header}.${body}.${sig}`;
}

const OUT = ".env.docker";
if (existsSync(OUT) && !process.argv.includes("--force")) {
  console.error(`${OUT} already exists. Pass --force to regenerate.`);
  console.error("Regenerating invalidates existing sessions and stored keys.");
  exit(1);
}

const jwtSecret = randomBytes(32).toString("hex");
const iat = Math.floor(Date.now() / 1000);
const exp = iat + 60 * 60 * 24 * 365 * 10; // 10 years

const anonKey = jwt({ role: "anon", iss: "supabase", iat, exp }, jwtSecret);
const serviceKey = jwt({ role: "service_role", iss: "supabase", iat, exp }, jwtSecret);
const dbPassword = randomBytes(18).toString("base64url");

const env = `# Generated by scripts/gen-supabase-keys.mjs — DO NOT COMMIT.
# Regenerating invalidates all existing sessions.

POSTGRES_PASSWORD=${dbPassword}
JWT_SECRET=${jwtSecret}

# Public (safe in the browser bundle)
NEXT_PUBLIC_SUPABASE_URL=http://localhost:8000
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${anonKey}

# SECRET — server only. Bypasses row-level security.
SUPABASE_SERVICE_ROLE_KEY=${serviceKey}

NEXT_PUBLIC_SITE_URL=http://localhost:3000

# Licence: leave empty on first boot, then read the fingerprint from
# Admin -> Settings -> Licence and paste the licence ABS issues.
ABS_TERRA_LICENSE=

# SMTP — required for OTP login, invites and MD approval codes.
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASS=

# Cloudflare Turnstile (optional; skipped entirely when empty)
NEXT_PUBLIC_TURNSTILE_SITE_KEY=
TURNSTILE_SECRET_KEY=
`;

writeFileSync(OUT, env);
console.log(`Wrote ${OUT}\n`);
console.log("JWT secret   :", jwtSecret.slice(0, 16) + "…");
console.log("anon key     :", anonKey.slice(0, 32) + "…");
console.log("service_role :", serviceKey.slice(0, 32) + "…");
console.log("\nNext: docker compose up -d");
